const root = document.documentElement;
const readPreference = key => { try { return localStorage.getItem(key); } catch { return null; } };
const savePreference = (key, value) => { try { localStorage.setItem(key, value); } catch { /* Preferences are optional. */ } };
let language = ['en', 'sk'].includes(readPreference('language')) ? readPreference('language') : 'en';
const themeButton = document.getElementById('theme-toggle');
const menuButton = document.getElementById('menu-toggle');
const navigation = document.getElementById('navigation');
let draftPrepared = false;
function updateThemeLabel() {
    themeButton.setAttribute('aria-label', translations[language][root.dataset.theme === 'dark' ? 'theme.light' : 'theme.dark']);
    themeButton.setAttribute('aria-pressed', String(root.dataset.theme === 'dark'));
    document.querySelector('meta[name="theme-color"]').content = root.dataset.theme === 'dark' ? '#171918' : '#f8f7f4';
}
function setLanguage(next) {
    language = next;
    root.lang = language;
    const copy = translations[language];
    document.querySelectorAll('[data-translate]').forEach(el => { el.textContent = copy[el.dataset.translate]; });
    document.querySelectorAll('[data-translate-placeholder]').forEach(el => { el.placeholder = copy[el.dataset.translatePlaceholder]; });
    document.querySelectorAll('[data-language]').forEach(el => el.setAttribute('aria-pressed', String(el.dataset.language === language)));
    menuButton.setAttribute('aria-label', copy.menu);
    navigation.setAttribute('aria-label', language === 'sk' ? 'Hlavná navigácia' : 'Main navigation');
    document.querySelector('.language-switch').setAttribute('aria-label', language === 'sk' ? 'Jazyk' : 'Language');
    document.title = language === 'sk' ? 'TESTX | QA konzultácie a testovanie softvéru' : 'TESTX | QA Consulting & Software Testing';
    const description = language === 'sk' ? 'QA konzultácie, testovanie softvéru, automatizácia a školenia tímov. S TESTX vytvárajte kvalitnejší softvér a nasadzujte s istotou.' : 'QA consulting, software testing, automation and team training. TESTX helps you build better software and release with confidence.';
    document.querySelector('meta[name="description"]').content = description;
    ['og:title', 'twitter:title'].forEach(key => document.querySelector(`meta[property="${key}"],meta[name="${key}"]`).content = document.title);
    ['og:description', 'twitter:description'].forEach(key => document.querySelector(`meta[property="${key}"],meta[name="${key}"]`).content = description);
    document.querySelector('meta[property="og:locale"]').content = language === 'sk' ? 'sk_SK' : 'en_GB';
    document.querySelector('meta[property="og:locale:alternate"]').content = language === 'sk' ? 'en_GB' : 'sk_SK';
    if (draftPrepared) document.getElementById('form-status').textContent = copy['contact.status'];
    updateThemeLabel();
    savePreference('language', language);
}
document.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.language)));
themeButton.addEventListener('click', () => {
    root.dataset.theme = root.dataset.theme === 'dark' ? 'light' : 'dark';
    savePreference('theme', root.dataset.theme);
    updateThemeLabel();
});
function closeMenu() { menuButton.setAttribute('aria-expanded', 'false'); navigation.classList.remove('is-open'); }
menuButton.addEventListener('click', () => {
    const open = menuButton.getAttribute('aria-expanded') !== 'true';
    menuButton.setAttribute('aria-expanded', String(open));
    navigation.classList.toggle('is-open', open);
});
navigation.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));
document.addEventListener('keydown', event => { if (event.key === 'Escape' && menuButton.getAttribute('aria-expanded') === 'true') { closeMenu(); menuButton.focus(); } });
document.addEventListener('click', event => { if (!event.target.closest('.nav-shell')) closeMenu(); });
matchMedia('(min-width: 761px)').addEventListener('change', closeMenu);
document.getElementById('contact-form').addEventListener('submit', event => {
    event.preventDefault();
    const form = event.currentTarget;
    if (!form.reportValidity()) return;
    const fields = new FormData(form);
    const copy = translations[language];
    const subject = `${copy['contact.subject']} ${fields.get('name').trim()}`;
    const body = `${copy['contact.name']}: ${fields.get('name').trim()}\n${copy['contact.email']}: ${fields.get('email').trim()}\n\n${fields.get('message').trim()}`;
    draftPrepared = true;
    const status = document.getElementById('form-status');
    status.hidden = false;
    status.textContent = copy['contact.status'];
    window.location.href = `mailto:testx.skuci@gmail.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
});
document.getElementById('year').textContent = new Date().getFullYear();
